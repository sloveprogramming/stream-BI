"""指标字典的错误类型。

刻意分成四类，因为它们的处理方式完全不同：

- **定义写错**（缺公式、引用了不存在的列）→ 抛错，必须改文件。这属于「人写错了」，
  越早暴露越好；
- **环境未就绪**（指标锚定的数据集还没上架）→ 不阻塞字典加载，只把该指标标记为
  不可用。数据集是运行时上架的，代码仓库不该强制「某个数据集必须已存在」；
- **引用了不存在的指标** → 抛错，并且**必须列出可用清单** —— 否则排错人只能去翻文件；
- **指标存在但当前不可用** → 单独一类，错误信息要说清是环境问题而非笔误。

不做成一个大异常类，是因为调用方对这些情况的反应不同：
前三类都是「拒绝这次操作」，但第四类的错误提示要指向「去注册数据集」而不是「去改定义」。
"""


class MetricError(Exception):
    """指标字典相关错误的基类。"""


class MetricValidationError(MetricError):
    """指标定义本身不合法 —— 文件里的内容需要改。"""


class MetricNotFoundError(MetricError):
    """引用了字典里没有的指标。"""


class MetricUnavailableError(MetricError):
    """指标存在，但它锚定的数据集在当前环境尚未上架。

    与 `MetricNotFoundError` 区分开：这个不是笔误，是环境没准备好，
    提示语应该指向「去注册数据集 / 跑种子脚本」，而不是「去改指标名」。
    """
